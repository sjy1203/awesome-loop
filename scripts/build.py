class Ctx:
    """Everything the generators read: entries, vocab labels and metrics."""

    def __init__(self):
        data = V.load_all()
        self.vocab = V.load_vocab()
        self.papers = [e for _, e in data["paper"]]
        self.models = [e for _, e in data["model"]]
        self.claims = sorted((e for _, e in data["claim"]), key=lambda c: c["id"])
        self.by_id = {p["id"]: p for p in self.papers}
        self.deep = [p for p in self.papers if p["tier"] == "deep"]
        self.core = [p for p in self.papers if p["focus"] == "core"]
        self.metrics, self.old = load_metrics()
        trend = os.path.join(ROOT, "data", "trend.json")
        self.trend = json.load(open(trend, encoding="utf-8")) if os.path.exists(trend) else None

    def label(self, section, value, lang):
        return self.vocab[section][value][lang]

    def name(self, pid):
        p = self.by_id[pid]
        return p.get("short") or p["title"]


def load_metrics():
    """latest.json and the newest history snapshot that is at least 28 days older (for change counts)."""
    d = os.path.join(ROOT, "data", "metrics")
    path = os.path.join(d, "latest.json")
    if not os.path.exists(path):
        return {}, {}
    with open(path, encoding="utf-8") as f:
        latest = json.load(f)
    old, hist = {}, os.path.join(d, "history")
    if latest.get("date") and os.path.isdir(hist):
        cutoff = (datetime.date.fromisoformat(latest["date"]) - datetime.timedelta(days=28)).isoformat()
        names = sorted(n for n in os.listdir(hist) if n.endswith(".json") and n[:-5] <= cutoff)
        if names:
            with open(os.path.join(hist, names[-1]), encoding="utf-8") as f:
                old = json.load(f)
    return latest, old


def gh_repo(url):
    """owner/name for a github.com URL, else None."""
    if url and url.startswith("https://github.com/"):
        parts = url[len("https://github.com/"):].strip("/").split("/")
        if len(parts) >= 2:
            return f"{parts[0]}/{parts[1]}"
    return None


def hf_model_repo(url):
    """owner/name for a huggingface.co model URL (not datasets, spaces or collections), else None."""
    prefix = "https://huggingface.co/"
    if not url.startswith(prefix):
        return None
    parts = url[len(prefix):].strip("/").split("/")
    if len(parts) < 2 or parts[0] in ("datasets", "spaces", "collections", "papers"):
        return None
    return f"{parts[0]}/{parts[1]}"


def fmt_count(new, old):
    s = f"{new:,}"
    if isinstance(old, int) and new != old:
        s += f" ({new - old:+,})"
    return s


def paper_metrics(ctx, p, lang):
    ui, pid = UI[lang], p["id"]
    cur = ctx.metrics.get("papers", {}).get(pid, {})
    old = ctx.old.get("papers", {}).get(pid, {})
    parts = []
    if cur.get("citations") is not None:
        parts.append(f"{ui['cites']} {fmt_count(cur['citations'], old.get('citations'))}")
    repo = gh_repo(p.get("links", {}).get("code"))
    stars = ctx.metrics.get("repos", {}).get(repo, {}).get("stars") if repo else None
    if stars is not None:
        parts.append(f"{ui['stars']} {fmt_count(stars, ctx.old.get('repos', {}).get(repo, {}).get('stars'))}")
    if cur.get("hf_upvotes") is not None:
        parts.append(f"{ui['hf']} {fmt_count(cur['hf_upvotes'], old.get('hf_upvotes'))}")
    if cur.get("hn_points"):
        parts.append(f"{ui['hn']} {fmt_count(cur['hn_points'], old.get('hn_points'))}")
    return " · ".join(parts) or "-"


def model_metrics(ctx, m, lang):
    ui = UI[lang]
    cur = [ctx.metrics.get("models", {}).get(r) for r in m["hf"]]
    cur = [c for c in cur if c]
    if not cur:
        return "-"
    old = [ctx.old.get("models", {}).get(r) or {} for r in m["hf"]]
    dl, likes = sum(c.get("downloads", 0) for c in cur), sum(c.get("likes", 0) for c in cur)
    old_dl = sum(o.get("downloads", 0) for o in old) if all(old) else None
    old_likes = sum(o.get("likes", 0) for o in old) if all(old) else None
    return f"{ui['downloads']} {fmt_count(dl, old_dl)} · {ui['likes']} {fmt_count(likes, old_likes)}"


def esc(s):
    return html.escape(str(s), quote=True)


def cell(s):
    """Make a value safe inside a markdown table cell."""
    return str(s).replace("|", "\\|").replace("\n", " ")


def row(cells):
    return "| " + " | ".join(cell(c) for c in cells) + " |"


def table_head(cols, right=()):
    """Header row and separator; columns whose index is in `right` are right-aligned (numbers)."""
    return [row(cols), "|" + "".join("---:|" if i in right else "---|" for i in range(len(cols)))]


def n_blocks(layers):
    """Blocks to draw: the layer count, one block per 10% for a share of the stack, three outlines if unknown."""
    if layers == "?":
        return 3
    return layers if isinstance(layers, int) else max(1, round(int(layers[:-1]) / 10))


def seg_label(s):
    return s.get("label") or f"{ROLE[s['role']]}{s['layers']}"


def glyph_text(p):
    """One-line text form of the fingerprint, used as alt text and in llms.txt."""
    out = []
    for s in p["loop"]["segments"]:
        if isinstance(s["layers"], int):
            size = f"{s['layers']} layer" + ("s" if s["layers"] != 1 else "")
        elif s["layers"] == "?":
            size = "layer count not stated"
        else:
            size = f"{s['layers']} of layers"
        lab = f"{s['label']} ({size})" if s.get("label") else f"{s['role']} {size}"
        if s["role"] == "core":
            lab = f"[{lab}] x {s['passes']['train']}" if "passes" in s else f"[{lab}] x T"
        out.append(lab)
    f = p["facets"]
    return f"{' -> '.join(out)}; injection {f['injection']}; KV {f['kv']}"


def glyph_svg(p):
    """Fingerprint: grey blocks = layers run once, blue blocks = the looped core, arrow = passes in training."""
    bw, gap, sgap, top, bh = 9, 3, 12, 30, 18
    x, shapes, texts, lefts, rights = 0.0, [], [], [0.0], [0.0]
    for s in p["loop"]["segments"]:
        core, shown = s["role"] == "core", min(n_blocks(s["layers"]), 12)
        blocks_w = shown * (bw + gap) - gap
        slot = max(blocks_w, len(seg_label(s)) * CHAR_W)  # wide labels push the next segment right
        x = x0 = x + (slot - blocks_w) / 2
        for _ in range(shown):
            fill = CORE if core else EDGE
            if s["layers"] == "?":  # unknown count: dashed outlines
                shapes.append(f'<rect x="{x + 0.5:g}" y="{top + 0.5}" width="{bw - 1}" height="{bh - 1}" rx="2" '
                              f'fill="none" stroke="{fill}" stroke-dasharray="2 2"/>')
            else:
                shapes.append(f'<rect x="{x:g}" y="{top}" width="{bw}" height="{bh}" rx="2" fill="{fill}"/>')
            x += bw + gap
        x1 = x - gap
        mid = (x0 + x1) / 2
        labels = [(mid, top + bh + 13, seg_label(s), "")]
        if core:
            shapes.append(f'<path d="M{x1:g},{top - 3} C{x1:g},{top - 17} {x0:g},{top - 17} {x0:g},{top - 8}" '
                          f'fill="none" stroke="{CORE}" stroke-width="1.5"/>')
            shapes.append(f'<path d="M{x0 - 3.5:g},{top - 9} L{x0 + 3.5:g},{top - 9} L{x0:g},{top - 2} Z" '
                          f'fill="{CORE}"/>')
            labels.append((mid, 11, "\u00d7" + (s["passes"]["train"] if "passes" in s else "T"), "p"))
        for lx, ly, txt, cls in labels:
            w = len(txt) * CHAR_W
            lefts.append(mid - w / 2)
            rights.append(mid + w / 2)
            texts.append((lx, ly, txt, "middle", cls))
        x = x1 + (slot - blocks_w) / 2 + sgap
    bx = x + 2
    for i, txt in enumerate((f"inj \u00b7 {p['facets']['injection']}", f"KV \u00b7 {p['facets']['kv']}")):
        texts.append((bx, top + 7 + 12 * i, txt, "start", ""))
        rights.append(bx + len(txt) * CHAR_W)
    off = round(max(0.0, 4 - min(lefts)), 1)
    width = round(max(rights) + off + 6, 1)
    alt = esc(glyph_text(p))
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width:g}" height="66" viewBox="0 0 {width:g} 66" '
           f'role="img" aria-label="{alt}">',
           f"<title>{alt}</title>",
           "<style>@media (prefers-color-scheme:dark){text{fill:#9198a1}text.p{fill:#4493f8}}</style>",
           f'<g transform="translate({off:g},0)" font-family="-apple-system,BlinkMacSystemFont,Segoe UI,'
           f'Helvetica,Arial,sans-serif" font-size="10">', *shapes]
    for tx, ty, txt, anchor, cls in texts:
        attrs = f' class="p" fill="{CORE}"' if cls else ' fill="#57606a"'
        out.append(f'<text x="{tx:g}" y="{ty:g}" text-anchor="{anchor}"{attrs}>{esc(txt)}</text>')
    return "\n".join(out + ["</g>", "</svg>"]) + "\n"


