def models_table(ctx, lang):
    ui = UI[lang]
    out = [f"## {ui['m_head']}", ""]
    if not ctx.models:
        return out + [ui["m_empty"], ""]
    out += table_head(ui["cols_m"])
    for m in sorted(ctx.models, key=lambda m: m["name"].lower()):
        p = ctx.by_id[m["paper"]]
        name = f"[{m['name']}](https://huggingface.co/{m['hf'][0]})"
        if len(m["hf"]) > 1:  # the full list is on the paper's card
            name += " " + ui["more"].format(n=len(m["hf"]) - 1)
        paper = f"[{ctx.name(p['id'])}](docs/{lang}/{p['id']}.md)" if p["tier"] == "deep" else ctx.name(p["id"])
        params = m["params"] + (f"<br>{ui['active']} {m['active_params']}" if m.get("active_params") else "")
        passes = m["passes"]["default"] + (f" / {m['passes']['range']}" if m["passes"].get("range") else "")
        runs = ", ".join(ctx.label("inference", i, lang) for i in m["inference"])
        out.append(row([name, paper, params, m["tokens"], passes, ctx.label("kv", m["kv"], lang),
                        m.get("context", "-"), m["license"], runs, model_metrics(ctx, m, lang)]))
    return out + [""]


def all_papers(ctx, lang):
    """Every paper (deep and radar) grouped by category, newest first."""
    ui = UI[lang]
    out = [f"## {ui['all_head']}", "", ui["all_note"], ""]
    for cat in ctx.vocab["category"]:
        group = sorted((p for p in ctx.papers if p["category"] == cat), key=lambda p: (p["date"], p["id"]),
                       reverse=True)
        if not group:
            continue
        out += [f"### {ctx.label('category', cat, lang)} ({len(group)})", ""] + table_head(ui["cols_all"])
        for p in group:
            title = f"[{p['title']}]({p['links']['paper']})"
            if p["tier"] == "deep":
                title += f" · **[{ui['deep_tag']}](docs/{lang}/{p['id']}.md)**"
            who = p["authors"][0] + (f" {ui['et_al']}" if len(p["authors"]) > 1 else "")
            venue = p.get("venue", "arXiv")
            sub = venue if p["authors"][0] in venue else who + ("" if venue == "arXiv" else f" · {venue}")
            out.append(row([p["date"], f"{title}<br><sub>{sub}</sub>", p["tldr"][lang], links_md(p, lang),
                            paper_metrics(ctx, p, lang)]))
        out.append("")
    return out


def card(ctx, p, lang):
    """docs/<lang>/<id>.md: the full deep card."""
    ui, pid, q, b, f = UI[lang], p["id"], p["quickread"], p["budget"], p["facets"]
    out = [HEADER, f"# {p['short']}: {p['title']}", "", ui["lang_links"].format(name=f"{pid}.md") + " · " + ui["back"],
           "", f"<sub>{venue_line(p)} · {p['date']} · {', '.join(p['orgs'])}</sub>", "",
           f'<img src="../../assets/glyphs/{pid}.svg" alt="{esc(glyph_text(p))}">', "", f"> {p['tldr'][lang]}", "",
           f"**{ui['k_category']}**{ui['colon']}{ctx.label('category', p['category'], lang)} · "
           f"**{ui['k_status']}**{ui['colon']}{ctx.label('status', p['status'], lang)} · "
           f"**{ui['k_metrics']}**{ui['colon']}{paper_metrics(ctx, p, lang)}", "", links_md(p, lang), "",
           f"## {ui['h_problem']}", "", q["problem"][lang], "", f"## {ui['h_method']}", ""]
    out += [f"- {m}" for m in q["method"][lang]] + ["", f"## {ui['h_layout']}", ""]
    out += table_head([ui["k_facet"], ui["k_value"]])
    out += [row([ui["facet"][k], ctx.label(k, f[k], lang)]) for k in FACETS]
    for s in p["loop"]["segments"]:
        if s["role"] == "core" and "passes" in s:
            ps = s["passes"]
            out.append(row([f"{ui['passes']} ({seg_label(s)})", f"{ui['train']} {ps['train']}" +
                            (f"; {ui['test']} {ps['test']}" if ps.get("test") else "")]))
        if s.get("bptt"):
            out.append(row([f"{ui['bptt']} ({seg_label(s)})", s["bptt"]]))
    if p["loop"].get("note"):
        out += ["", p["loop"]["note"][lang]]
    out += ["", f"## {ui['h_results']}", ""]
    for r in p["results"]:
        out += [f"**{r['setting']}** · {r['metric']} · {r['ref']}", ""] + table_head([ui["k_variant"], ui["k_value"]])
        out += [row([k, v]) for k, v in r["values"].items()]
        out += ["", r["note"][lang], ""] if r.get("note") else [""]
    if p.get("findings"):
        out += [f"## {ui['h_findings']}", ""] + [f"- {x[lang]} ({x['ref']})" for x in p["findings"]] + [""]
    colon = ui["colon"]
    out += [f"## {ui['h_budget']}", "", f"- **{ui['k_baseline']}**{colon}{b['baseline'][lang]}",
            f"- **{ui['k_matched']}**{colon}{budget_items(ctx, b['matched'], lang)}",
            f"- **{ui['k_not']}**{colon}{budget_items(ctx, b['not_matched'], lang)}",
            f"- **{ui['k_tuned']}**{colon}{ctx.label('baseline_tuned', b['baseline_tuned'], lang)}",
            f"- **{ui['k_headline']}**{colon}{b['headline'][lang]} ({b['ref']})", "", f"## {ui['h_caveats']}", ""]
    out += [f"- {x}" for x in q["caveats"][lang]] + [""]
    if q.get("hooks"):
        out += [f"## {ui['h_hooks']}", ""] + [f"- {h}" for h in q["hooks"][lang]] + [""]
    keys = ("code", "weights", "configs", "data")
    out += [f"## {ui['h_repro']}", ""] + table_head([ui["repro"][k] for k in keys])
    out += [row([ctx.label("repro", p["reproducibility"][k], lang) for k in keys]), ""]
    models = [m for m in ctx.models if m["paper"] == pid]
    if models:
        out += [f"## {ui['h_models']}", ""]
        out += [f"- {m['name']}: " + ", ".join(f"[{r}](https://huggingface.co/{r})" for r in m["hf"]) for m in models]
        out.append("")
    rel = [(c, e) for c in ctx.claims for e in c["evidence"] if e["paper"] == pid]
    if rel:
        out += [f"## {ui['h_questions']}", ""]
        out += [f"- [{c['question'][lang]}](questions.md#{c['id']}) ({ctx.label('stance', e['stance'], lang)})"
                for c, e in rel] + [""]
    out += [f"## {ui['h_authors']}", "", ", ".join(p["authors"]), ""]
    return "\n".join(out)


def questions_md(ctx, lang):
    ui = UI[lang]
    out = [HEADER, f"# {ui['q_title']}", "", ui["lang_links"].format(name="questions.md") + " · " + ui["back"], ""]
    for c in ctx.claims:
        out += [f'## <a id="{c["id"]}"></a>{c["question"][lang]}', "",
                f"**{ctx.label('claim_status', c['status'], lang)}** · {ui['updated']} {c['updated']}", "",
                c["summary"][lang], ""] + table_head(ui["q_cols"])
        for e in c["evidence"]:
            p = ctx.by_id[e["paper"]]
            name = f"[{ctx.name(p['id'])}]({p['id']}.md)" if p["tier"] == "deep" else f"[{p['title']}]({p['links']['paper']})"
            out.append(row([name, ctx.label("stance", e["stance"], lang), e["setting"], e["finding"][lang], e["ref"]]))
        out.append("")
    return "\n".join(out)


def to_json(obj):
    return json.dumps(obj, ensure_ascii=False, indent=1) + "\n"


def exports(ctx):
    papers = []
    for p in sorted(ctx.papers, key=lambda p: p["id"]):
        e = dict(p)
        if p["tier"] == "deep":
            e["glyph"] = glyph_text(p)
            e["card"] = {lang: f"{RAW}docs/{lang}/{p['id']}.md" for lang in LANGS}
        papers.append(e)
    return {"data/papers.json": to_json({"schema": "schema/paper.schema.json", "papers": papers}),
            "data/models.json": to_json({"schema": "schema/model.schema.json",
                                         "models": sorted(ctx.models, key=lambda m: m["id"])}),
            "data/claims.json": to_json({"schema": "schema/claim.schema.json", "claims": ctx.claims})}


def llms(ctx, cards_en, questions_en):
    """llms.txt (index, llmstxt.org layout) and llms-full.txt (every English deep card in one file)."""
    items = ctx.vocab["budget_item"]
    legend = ", ".join(f"{k} = {v['en']}" for k, v in items.items())
    out = ["# Awesome Loop", "",
           "> Looped and recurrent-depth language models. Each deep card records the loop layout, what the main "
           "comparison holds fixed, the paper's results with table or figure references, and caveats taken from the "
           "paper. All numbers are author-reported; nothing is converted or extrapolated. Comparison keys: " + legend +
           ".",
           "", "## Deep cards", ""]
    for p in sorted(ctx.deep, key=lambda p: p["date"], reverse=True):
        b = p["budget"]
        out.append(f"- [{p['short']}]({RAW}docs/en/{p['id']}.md): {p['tldr']['en']} Layout: {glyph_text(p)}. "
                   f"Held fixed: {', '.join(b['matched']) or 'none'}; differs: {', '.join(b['not_matched']) or 'none'}.")
    radar = sorted((p for p in ctx.papers if p["tier"] == "radar"), key=lambda p: (p["date"], p["id"]), reverse=True)
    if radar:
        out += ["", "## Other papers", ""]
        out += [f"- [{p['title']}]({p['links']['paper']}): {p['tldr']['en']} Category: {p['category']}; {p['date']}."
                for p in radar]
    out += ["", "## Open questions", ""]
    out += [f"- [{c['question']['en']}]({RAW}docs/en/questions.md#{c['id']}): {c['status']}; {c['summary']['en']}"
            for c in ctx.claims]
    out += ["", "## Open models", ""]
    for m in sorted(ctx.models, key=lambda m: m["name"].lower()):
        out.append(f"- [{m['name']}](https://huggingface.co/{m['hf'][0]}): paper {m['paper']}; {m['params']} params; "
                   f"{m['tokens']} training tokens; passes {m['passes']['default']}; KV {m['kv']}; license {m['license']}.")
    out += ["", "## Data", "",
            f"- [papers.json]({RAW}data/papers.json): every paper entry (deep and radar) as JSON",
            f"- [models.json]({RAW}data/models.json) and [claims.json]({RAW}data/claims.json)",
            f"- [metrics]({RAW}data/metrics/latest.json): citations, stars, Hugging Face upvotes and downloads",
            f"- [schema]({REPO}/tree/main/schema): field definitions and allowed values",
            f"- [llms-full.txt]({RAW}llms-full.txt): all English deep cards in one file",
            "", "## Optional", "", f"- [Chinese README]({RAW}README.zh-CN.md)", ""]
    strip = (HEADER.strip(),)
    full = ["# Awesome Loop: all deep cards", ""]
    for text in cards_en + [questions_en]:
        full += [ln for ln in text.splitlines() if ln.strip() not in strip and not ln.startswith("<img ")] + [""]
    return "\n".join(out), "\n".join(full)


def build_outputs(ctx):
    """{relative path: file content} for every generated file."""
    out = {UI[lang]["readme"]: readme(ctx, lang) for lang in LANGS}
    cards_en = []
    for p in sorted(ctx.deep, key=lambda p: p["date"], reverse=True):
        out[f"assets/glyphs/{p['id']}.svg"] = glyph_svg(p)
        for lang in LANGS:
            out[f"docs/{lang}/{p['id']}.md"] = card(ctx, p, lang)
        cards_en.append(out[f"docs/en/{p['id']}.md"])
    for lang in LANGS:
        out[f"docs/{lang}/questions.md"] = questions_md(ctx, lang)
    out.update(exports(ctx))
    out["llms.txt"], out["llms-full.txt"] = llms(ctx, cards_en, out["docs/en/questions.md"])
    return out


def read(rel):
    path = os.path.join(ROOT, rel)
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as f:
        return f.read()


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if a generated file is out of date")
    args = ap.parse_args()
    errors = V.validate()
    if errors:
        print("\n".join(errors) + f"\n{len(errors)} validation problem(s)")
        return 1
    out = build_outputs(Ctx())
    stale = []
    for d in GENERATED_DIRS:
        full = os.path.join(ROOT, d)
        if os.path.isdir(full):
            stale += [f"{d}/{n}" for n in sorted(os.listdir(full)) if f"{d}/{n}" not in out]
    changed = [rel for rel, text in out.items() if read(rel) != text]
    if args.check:
        for rel in changed:
            print(f"out of date: {rel}")
        for rel in stale:
            print(f"stale: {rel}")
        if changed or stale:
            print("run `python3 scripts/build.py` and commit the result")
            return 1
        print(f"ok: {len(out)} generated files are up to date")
        return 0
    for rel in changed:
        path = os.path.join(ROOT, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(out[rel])
    for rel in stale:
        os.remove(os.path.join(ROOT, rel))
    print(f"wrote {len(changed)} of {len(out)} files, removed {len(stale)} stale")
    return 0


if __name__ == "__main__":
    sys.exit(main())
